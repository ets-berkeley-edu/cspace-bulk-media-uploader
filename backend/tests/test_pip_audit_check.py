"""pip_audit_check.py: pip-audit fails a pull request only for the pinned packages it changes."""

import importlib.util
from pathlib import Path

import pytest

_spec = importlib.util.spec_from_file_location("pip_audit_check", Path(__file__).parent.parent / "pip_audit_check.py")
pac = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pac)


def pins(*lines):
    return "#\n# autogenerated by pip-compile\n#\n" + "".join(
        f"{line} \\\n    --hash=sha256:{'0' * 64}\n    # via -r requirements.in\n" for line in lines
    )


def report(*dependencies):
    return {"dependencies": [
        {"name": name, "version": version, "vulns": [
            {"id": vid, "fix_versions": fixes, "aliases": ["GHSA-aaaa-bbbb-cccc", "CVE-2026-1"], "description": "x"}
            for vid, fixes in vulns
        ]}
        for name, version, vulns in dependencies
    ] + [{"name": "bmu", "skip_reason": "not on PyPI"}], "fixes": []}


def test_pinned_versions_by_canonical_name_across_files():
    versions = pac.pinned_versions([pins("Jinja2==3.1.6", "zope.interface==7.0", "uvicorn[standard]==0.40.0"),
                                    pins("click==8.3.0"), pins("click==8.4.2")])
    assert versions == {"jinja2": {"3.1.6"}, "zope-interface": {"7.0"}, "uvicorn": {"0.40.0"},
                        "click": {"8.3.0", "8.4.2"}}


def test_changed_packages_added_removed_or_moved():
    base = [pins("kept==1.0", "upgraded==1.0", "removed==1.0"), pins("moved==2.0")]
    head = [pins("kept==1.0", "upgraded==1.1", "moved==2.0"), pins("added==1.0")]
    assert pac.changed_packages(base, head) == {"upgraded", "removed", "added"}
    assert pac.changed_packages(base, base) == set()


def test_every_vulnerability_fails_without_changed():
    failures, warnings = pac.check([report(("requests", "2.0", [("PYSEC-1", ["2.1"])]), ("idna", "3.0", []))])
    assert failures == ["PYSEC-1 (GHSA-aaaa-bbbb-cccc, CVE-2026-1) in requests 2.0: fixed in 2.1"]
    assert warnings == []


def test_on_a_pull_request_only_changed_packages_fail():
    reports = [report(("Requests", "2.0", [("PYSEC-1", [])]), ("urllib3", "1.0", [("PYSEC-2", ["1.1"])]))]
    failures, warnings = pac.check(reports, changed={"urllib3"})
    assert failures == ["PYSEC-2 (GHSA-aaaa-bbbb-cccc, CVE-2026-1) in urllib3 1.0: fixed in 1.1"]
    assert warnings == [
        "PYSEC-1 (GHSA-aaaa-bbbb-cccc, CVE-2026-1) in requests 2.0: fixed in none yet "
        "(in a package this pull request doesn't change)"
    ]


def test_a_vulnerability_found_in_both_runs_is_listed_once():
    one = report(("idna", "3.0", [("PYSEC-3", ["3.1"])]))
    assert len(pac.check([one, one])[0]) == 1


@pytest.fixture
def run(monkeypatch, tmp_path):
    """main() in a folder of requirements files, with pip-audit and git replaced."""
    monkeypatch.chdir(tmp_path)
    monkeypatch.delenv("GITHUB_STEP_SUMMARY", raising=False)
    head = {name: pins("idna==3.0") for name in pac.FILES}
    head["requirements.txt"] = pins("idna==3.0", "requests==2.1")
    for name, text in head.items():
        (tmp_path / name).write_text(text)
    base = {name: pins("idna==3.0") for name in pac.FILES}
    base["requirements.txt"] = pins("idna==3.0", "requests==2.0")
    state = {"report": report(), "base": base}
    monkeypatch.setattr(pac, "_audit", lambda files: (state["report"], None))
    monkeypatch.setattr(pac, "_at_commit", lambda ref, path: state["base"].get(path) if ref == "HEAD^1" else None)

    def go(*argv):
        return pac.main(list(argv))
    go.state = state
    return go


def test_main_passes_with_a_warning_for_an_unchanged_package(run, capsys, tmp_path, monkeypatch):
    summary = tmp_path / "summary.md"
    monkeypatch.setenv("GITHUB_STEP_SUMMARY", str(summary))
    run.state["report"] = report(("idna", "3.0", [("PYSEC-3", ["3.1"])]))
    assert run("--changed-since", "HEAD^1") == 0
    out = capsys.readouterr().out
    assert "Compared with HEAD^1: 1 pinned package(s) changed (requests)." in out
    assert "::warning::PYSEC-3" in out
    assert "PYSEC-3" in summary.read_text()
    assert run() == 1  # the same report fails the full check


def test_main_fails_for_a_changed_package(run):
    run.state["report"] = report(("requests", "2.1", [("PYSEC-1", [])]))
    assert run("--changed-since", "HEAD^1") == 1


def test_main_is_strict_when_the_base_cannot_be_read(run, capsys):
    run.state["report"] = report(("idna", "3.0", [("PYSEC-3", ["3.1"])]))
    assert run("--changed-since", "nosuchref") == 1
    assert "checking every package" in capsys.readouterr().out


def test_main_fails_when_pip_audit_fails(run, monkeypatch):
    monkeypatch.setattr(pac, "_audit", lambda files: (None, "pip-audit gave no report"))
    assert run("--changed-since", "HEAD^1") == 1
